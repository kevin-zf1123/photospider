"""Independent scalar oracle for FIL-19B smaa_1x_low_luma_v1.

All observable arithmetic stages round to binary32. Image coordinates are
binary64 texel coordinates, with integer centers. Cached calls evaluate the
mathematical stage DAG and are useful for sparse large-image validation.
Lookup bytes are the pinned upstream assets, never generated by the runtime.
"""
from functools import lru_cache
from fractions import Fraction
import math
from pathlib import Path
import re
import struct

from oracle.ops.filter.common.core import rn


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def add(a, b):
    return f32(a + b)


def mul(a, b):
    return f32(a * b)


def div(a, b):
    return rn(Fraction(a) / Fraction(b), "float32")


def fma(a, b, c):
    return rn(Fraction(a) * Fraction(b) + Fraction(c), "float32")


def lerp(a, b, t):
    return add(mul(a, add(1.0, -t)), mul(b, t))


def bilinear(read, y, x):
    iy, ix = math.floor(y), math.floor(x)
    fy, fx = f32(y - iy), f32(x - ix)
    top = lerp(read(iy, ix), read(iy, ix + 1), fx)
    bottom = lerp(read(iy + 1, ix), read(iy + 1, ix + 1), fx)
    return lerp(top, bottom, fy)


@lru_cache(None)
def lookup_tables():
    root = Path(__file__).resolve().parents[4]
    folder = root / "plugins/ops/05-filter/smaa_resources"
    result = []
    for name in ("AreaTex.h", "SearchTex.h"):
        body = (folder / name).read_text().split("Bytes[] = {", 1)[1].split("}", 1)[0]
        result.append(bytes(int(s, 16) for s in re.findall(r"0x([0-9a-fA-F]{2})", body)))
    assert len(result[0]) == 160 * 560 * 2 and len(result[1]) == 64 * 16
    return tuple(result)


class Reference:
    def __init__(self, height, width, color, *, guide=None, components=1):
        self.h, self.w, self.color = height, width, color
        self.guide, self.components = guide, components
        self.area_bytes, self.search_bytes = lookup_tables()

    def clamp(self, y, x):
        return min(max(y, 0), self.h - 1), min(max(x, 0), self.w - 1)

    def source(self, y, x, c):
        return self.color(*self.clamp(y, x), c)

    @lru_cache(None)
    def luma(self, y, x):
        y, x = self.clamp(y, x)
        if self.guide is not None:
            return self.guide(y, x)
        if self.components == 1:
            return self.source(y, x, 0)
        products = [mul(self.source(y, x, c), f32(w))
                    for c, w in enumerate((.2126, .7152, .0722))]
        return add(add(products[0], products[1]), products[2])

    @lru_cache(None)
    def edge(self, y, x):
        y, x = self.clamp(y, x)
        center, left, top = self.luma(y, x), self.luma(y, x-1), self.luma(y-1, x)
        horizontal, vertical = abs(add(center, -left)), abs(add(center, -top))
        candidates = [horizontal >= f32(.15), vertical >= f32(.15)]
        if not any(candidates):
            return (0.0, 0.0)
        contrast = max(horizontal, vertical,
                       abs(add(center, -self.luma(y, x+1))),
                       abs(add(center, -self.luma(y+1, x))),
                       abs(add(left, -self.luma(y, x-2))),
                       abs(add(top, -self.luma(y-2, x))))
        return tuple(float(active and mul(2., delta) >= contrast)
                     for active, delta in zip(candidates, (horizontal, vertical)))

    def edge_linear(self, y, x, component):
        return bilinear(lambda yy, xx: self.edge(yy, xx)[component], y, x)

    def search_lookup(self, first, second, positive):
        x = fma(32., first, 33. if positive else 0.)
        y = fma(-32., second, 32.)
        def texel(yy, xx):
            i = min(max(yy, 0), 15) * 64 + min(max(xx, 0), 63)
            return div(float(self.search_bytes[i]), 255.)
        return bilinear(texel, y, x)

    def endpoint(self, y, x, axis, sign):
        initial = y if axis else x
        e = [1., 0.] if axis else [0., 1.]
        for _ in range(4):
            if e[0 if axis else 1] <= f32(.8281) or e[1 if axis else 0] != 0:
                break
            e = [self.edge_linear(y, x, c) for c in range(2)]
            if axis: y += sign * 2
            else: x += sign * 2
        if axis: e.reverse()
        correction = fma(-div(255., 127.), self.search_lookup(*e, sign > 0), 3.25)
        return add(f32((y if axis else x) - initial), -sign * correction)

    def area(self, distances, crossings):
        coords = [fma(16., float(round(mul(4., edge))), f32(math.sqrt(distance)))
                  for distance, edge in zip(distances, crossings)]
        def texel(y, x, c):
            i = (min(max(y, 0), 559) * 160 + min(max(x, 0), 159)) * 2 + c
            return div(float(self.area_bytes[i]), 255.)
        return tuple(bilinear(lambda y, x: texel(y, x, c), coords[1], coords[0])
                     for c in range(2))

    @lru_cache(None)
    def weight(self, y, x):
        y, x = self.clamp(y, x)
        west, north = self.edge(y, x)
        output = [0.] * 4
        if north:
            left = add(-.25, self.endpoint(y-.125, x-.25, False, -1))
            right = add(1.25, self.endpoint(y-.125, x+1.25, False, 1))
            crossing = (self.edge_linear(y-.25, x+left, 0),
                        self.edge_linear(y-.25, x+right+1, 0))
            output[0:2] = self.area((abs(round(left)), abs(round(right))), crossing)
        if west:
            top = add(-.25, self.endpoint(y-.25, x-.125, True, -1))
            bottom = add(1.25, self.endpoint(y+1.25, x-.125, True, 1))
            crossing = (self.edge_linear(y+top, x-.25, 1),
                        self.edge_linear(y+bottom+1, x-.25, 1))
            output[2:4] = self.area((abs(round(top)), abs(round(bottom))), crossing)
        return tuple(output)

    def output(self, y, x, c=0):
        center = self.weight(y, x)
        weights = [self.weight(y, x+1)[3], self.weight(y+1, x)[1],
                   center[2], center[0]]
        if add(add(add(weights[0], weights[1]), weights[2]), weights[3]) < f32(1e-5):
            return self.source(y, x, c)
        horizontal = max(weights[0], weights[2]) > max(weights[1], weights[3])
        positive, negative = ((weights[0], weights[2]) if horizontal
                              else (weights[1], weights[3]))
        total = add(positive, negative)
        a, b = div(positive, total), div(negative, total)
        read = lambda yy, xx: self.source(yy, xx, c)
        v0 = bilinear(read, y + (0 if horizontal else positive),
                      x + (positive if horizontal else 0))
        v1 = bilinear(read, y - (0 if horizontal else negative),
                      x - (negative if horizontal else 0))
        return add(mul(v0, a), mul(v1, b))
